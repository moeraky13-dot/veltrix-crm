def normalize_lang(lang):
    return lang if lang in SUPPORTED_LANGS else DEFAULT_LANG


def translate(lang, key, **kwargs):
    lang = normalize_lang(lang)
    text = MESSAGES.get(lang, MESSAGES[DEFAULT_LANG]).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def category_label(lang, category_row):
    """اسم الفئة حسب اللغة."""
    lang = normalize_lang(lang)
    slug = category_row['slug'] if hasattr(category_row, '__getitem__') else category_row.get('slug')
    labels = CATEGORY_LABELS.get(slug)
    if labels:
        return labels.get(lang, labels['ar'])
    return category_row['name']
